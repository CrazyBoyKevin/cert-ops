import assert from 'node:assert/strict';
import test from 'node:test';
import { readFile } from 'node:fs/promises';
import postcss from 'postcss';

const css = await readFile(new URL('../app/globals.css', import.meta.url), 'utf8');
const root = postcss.parse(css);
function value(selector, prop) {
  let result;
  root.walkRules(selector, rule => rule.walkDecls(prop, decl => { result = decl.value; }));
  return result;
}
test('shared surfaces and interactions use a monochrome palette', () => {
  for (const [name, expected] of Object.entries({ '--navy': '#171717', '--primary': '#262626', '--primary-dark': '#404040', '--text': '#202020', '--muted': '#737373', '--canvas': '#f5f5f5', '--line': '#e5e5e5' })) {
    assert.equal(value(':root', name), expected);
  }
  for (const selector of ['.primary-button', '.login-submit', '.switch.on']) assert.equal(value(selector, 'background'), 'var(--primary)');
  for (const selector of ['.login-shell', '.login-panel', '.language-option.selected', '.channel-card.enabled', '.project-navigation .group-item.selected, .project-navigation .group-entry.selected', '.modal-backdrop, .drawer-backdrop']) {
    root.walkRules(selector, rule => rule.walkDecls(decl => {
      for (const match of decl.value.matchAll(/#([0-9a-f]{6})(?:[0-9a-f]{2})?\b/gi)) {
        const hex = match[1]; assert.equal(hex.slice(0, 2), hex.slice(2, 4), selector); assert.equal(hex.slice(2, 4), hex.slice(4, 6), selector);
      }
      for (const match of decl.value.matchAll(/rgba?\((\d+),\s*(\d+),\s*(\d+)/g)) assert.ok(match[1] === match[2] && match[2] === match[3], selector);
    }));
  }
  assert.doesNotMatch(css, /filter:\s*grayscale/);
});
